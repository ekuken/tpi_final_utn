CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(60) NOT NULL,
  rol VARCHAR(10) NOT NULL CHECK (rol IN ('ADMIN','EMPLEADO')),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  descripcion VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS proveedores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  contacto VARCHAR(80),
  telefono VARCHAR(20),
  email VARCHAR(100),
  direccion VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  descripcion VARCHAR(150),
  precio NUMERIC(10,2) NOT NULL,
  precio_costo NUMERIC(10,2) NOT NULL DEFAULT 0,
  stock INT NOT NULL DEFAULT 0,
  stock_minimo INT NOT NULL DEFAULT 0,
  categoria_id BIGINT REFERENCES categorias(id),
  proveedor_id BIGINT REFERENCES proveedores(id),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMP NOT NULL,
  fecha_actualizacion TIMESTAMP,
  version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS movimientos_stock (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id BIGINT NOT NULL REFERENCES productos(id),
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA','SALIDA')),
  cantidad INT NOT NULL,
  stock_resultante INT NOT NULL,
  motivo VARCHAR(150),
  usuario_id BIGINT REFERENCES usuarios(id),
  fecha TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS ordenes_compra (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id BIGINT NOT NULL REFERENCES proveedores(id),
  estado VARCHAR(10) NOT NULL CHECK (estado IN ('PENDIENTE','RECIBIDA','CANCELADA')),
  observaciones VARCHAR(150),
  total NUMERIC(14,2) NOT NULL,
  usuario_id BIGINT REFERENCES usuarios(id),
  fecha_creacion TIMESTAMP NOT NULL,
  fecha_recepcion TIMESTAMP
);

CREATE TABLE IF NOT EXISTS orden_compra_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id BIGINT NOT NULL REFERENCES ordenes_compra(id),
  producto_id BIGINT NOT NULL REFERENCES productos(id),
  cantidad INT NOT NULL CHECK (cantidad > 0),
  costo_unitario NUMERIC(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS ventas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente VARCHAR(80),
  estado VARCHAR(10) NOT NULL CHECK (estado IN ('CONFIRMADA','ANULADA')),
  total NUMERIC(14,2) NOT NULL,
  usuario_id BIGINT REFERENCES usuarios(id),
  fecha TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS venta_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id BIGINT NOT NULL REFERENCES ventas(id),
  producto_id BIGINT NOT NULL REFERENCES productos(id),
  cantidad INT NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(10,2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_mov_producto ON movimientos_stock(producto_id);
CREATE INDEX IF NOT EXISTS idx_mov_fecha ON movimientos_stock(fecha);
CREATE INDEX IF NOT EXISTS idx_oc_items_orden ON orden_compra_items(orden_id);
CREATE INDEX IF NOT EXISTS idx_venta_items_venta ON venta_items(venta_id);
CREATE INDEX IF NOT EXISTS idx_ventas_fecha ON ventas(fecha);

